"""Tests for bin/odapkit-craft (tools/pcb-craft-check.py) on the fixtures in tests/fixtures/craft/.

good.kicad_pcb must pass every check and reach Q4; bad.kicad_pcb must fail every check. The boards
are generated by tests/fixtures/craft/make_fixture.py (KiCad's Python). Skipped without KiCad.

Run from the repository root: python3 -m unittest discover tests
"""
import json
import os
import shutil
import subprocess
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
TOOL = os.path.join(HERE, "..", "bin", "odapkit-craft")
FIX = os.path.join(HERE, "fixtures", "craft")
APP = os.environ.get("KICAD_APP", "/Applications/KiCad/KiCad.app")
KICAD_PY = os.environ.get("KICAD_PYTHON", os.path.join(
    APP, "Contents", "Frameworks", "Python.framework", "Versions", "Current", "bin", "python3"))
HAVE_CLI = os.path.exists(os.path.join(APP, "Contents", "MacOS", "kicad-cli")) or shutil.which("kicad-cli")

# Every check the script runs; each must pass on good and fail on bad.
CHECKS = {
    "CRAFT-08": "Q2", "CRAFT-10": "Q2", "CRAFT-11": "Q2", "CRAFT-12": "Q3", "CRAFT-13": "Q1",
    "CRAFT-14": "Q1", "CRAFT-20": "Q1", "CRAFT-21": "Q2", "CRAFT-22": "Q3", "CRAFT-23": "Q1",
    "CRAFT-24": "Q2", "CRAFT-30": "Q2", "CRAFT-31": "Q2", "CRAFT-32": "Q3", "CRAFT-33": "Q3",
    "CRAFT-34": "Q2", "CRAFT-36": "Q3", "CRAFT-42": "Q3", "CRAFT-44": "Q3", "CRAFT-46": "Q3",
    "CRAFT-48": "Q3", "CRAFT-49": "Q2", "CRAFT-50": "Q3", "CRAFT-51": "Q3", "CRAFT-60": "Q2",
    "CRAFT-61": "Q2", "CRAFT-62": "Q2", "CRAFT-71": "Q2",
}


def run(*args):
    return subprocess.run([TOOL, *args], capture_output=True, text=True)


def results(report):
    return {r["id"]: r for lv in report["levels"].values() for r in lv}


@unittest.skipIf(not os.path.exists(KICAD_PY), "KiCad's Python not found")
class Craft(unittest.TestCase):
    def check(self, board, *extra):
        r = run("check", "--json", *extra, os.path.join(FIX, board))
        self.assertIn(r.returncode, (0, 1), r.stderr)
        return r.returncode, json.loads(r.stdout)

    def test_good_passes_everything(self):
        code, report = self.check("good.kicad_pcb", "--no-drc")
        got = results(report)
        for cid, level in CHECKS.items():
            self.assertEqual(got[cid]["level"], level, cid)
            self.assertEqual(got[cid]["status"], "pass", (cid, got[cid]["findings"]))
        self.assertEqual(set(got), set(CHECKS))
        self.assertEqual(report["reached"], "Q4")
        self.assertEqual(report["target"], "Q4")  # from good.craft.toml
        self.assertEqual(code, 0)

    def test_bad_fails_everything(self):
        code, report = self.check("bad.kicad_pcb", "--no-drc")
        got = results(report)
        for cid in CHECKS:
            self.assertEqual(got[cid]["status"], "fail", cid)
        self.assertEqual(report["reached"], "Q0")  # no Q0 item without DRC; Q1 items fail
        self.assertEqual(code, 1)

    def test_target_and_debt(self):
        # good with a Q1 target: nothing fails, nothing is debt
        code, report = self.check("good.kicad_pcb", "--no-drc", "--target", "Q1")
        self.assertEqual((code, report["debt"]), (0, []))
        # bad with a Q0 target: no Q0 item fails without DRC, so the target is met and every
        # failure is debt
        code, report = self.check("bad.kicad_pcb", "--no-drc", "--target", "Q0")
        self.assertEqual(code, 0)
        self.assertEqual(report["reached"], "Q0")
        self.assertEqual(set(report["debt"]), set(CHECKS))

    @unittest.skipIf(not HAVE_CLI, "kicad-cli not found")
    def test_drc_fold(self):
        _, good = self.check("good.kicad_pcb")
        _, bad = self.check("bad.kicad_pcb")
        self.assertEqual(results(good)["FIX-01"]["status"], "pass")
        fix = results(bad)["FIX-01"]
        self.assertEqual((fix["status"], fix["level"], fix["enforcement"]), ("fail", "Q2", "DRC"))
        self.assertEqual(results(bad)["DRC"]["level"], "Q0")

    def test_usage(self):
        self.assertEqual(run("--help").returncode, 0)
        self.assertEqual(run().returncode, 2)
        self.assertEqual(run("lint").returncode, 2)
        self.assertEqual(run("check").returncode, 2)
        self.assertEqual(run("check", "--target", "Q9", os.path.join(FIX, "good.kicad_pcb")).returncode, 2)


if __name__ == "__main__":
    unittest.main()
