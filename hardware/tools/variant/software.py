"""Software outputs of a variant (RFC 0011 rule 7 and rule 8; docs/specs/variant-tool.md §7).

- `capabilities()`: `opendap.variant-capabilities/v1`, the blocks a variant fits and what each one gives software
  (devicetree node and compatibles, `org.opendap.hw.*` interfaces, device-description sections), so software enables
  what is present and treats what is absent as absent (SYS-040). It is a fragment for the board's device description
  (`opendap.device-description/v1`); the description has no section for it yet (consumer side open).
- `devicetree()`: `opendap.variant-devicetree/v1` and an overlay source fragment with `status = "okay"` or
  `"disabled"` for each block whose catalog record names its devicetree node; a block that names none is listed as
  skipped, with the reason.

Both are pure functions of the variant file and its catalog: the same inputs give the same bytes.
"""
import re

LABEL = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")
PATH = re.compile(r"/[^\s{}]*")


def _entry(variant, bid):
    e = variant.blocks.get(bid)
    return e if isinstance(e, dict) else {}


def capabilities(variant, catalog):
    blocks = []
    for bid in sorted(catalog.active()):
        blk, e = catalog.blocks[bid], _entry(variant, bid)
        sw = blk.software
        blocks.append({"id": bid, "function": blk.function, "state": e.get("state"), "alternate": e.get("alternate"),
                       "params": e.get("params", {}), "open": e.get("open"),
                       "present": e.get("state") in ("fit", "alternate"),
                       "requirements": [{"id": r, "priority": p} for r, p in blk.requirements],
                       "devicetree": {"node": sw["devicetree"], "compatible": list(sw["compatible"])},
                       "provides": list(sw["provides"]), "description": list(sw["description"])})
    present = [b for b in blocks if b["present"]]
    return {"schema": "opendap.variant-capabilities/v1", "board": variant.data.get("board"), "variant": variant.name,
            "kind": variant.data.get("kind"), "status": variant.data.get("status"),
            "present": [b["id"] for b in present], "absent": [b["id"] for b in blocks if not b["present"]],
            "provides": sorted({p for b in present for p in b["provides"]}),
            "description_sections": sorted({s for b in present for s in b["description"]}),
            "open": [{"block": b["id"], "open": b["open"]} for b in blocks if b["open"]],
            "blocks": blocks}


def devicetree(variant, catalog, source):
    """(document, overlay source text). source: the variant file's path as it is to be named in the fragment."""
    blocks, nodes = [], {}
    for bid in sorted(catalog.active()):
        e = _entry(variant, bid)
        node = catalog.blocks[bid].software["devicetree"]
        status = "okay" if e.get("state") in ("fit", "alternate") else "disabled"
        b = {"block": bid, "state": e.get("state"), "alternate": e.get("alternate"), "status": status, "node": None,
             "compatible": list(catalog.blocks[bid].software["compatible"]), "skipped": None, "open": e.get("open")}
        if not node:
            b["skipped"] = "no devicetree node named in the catalog's software field"
        elif LABEL.fullmatch(node) or PATH.fullmatch(node):
            b["node"] = node
            nodes.setdefault(node, []).append(b)
        else:
            b["skipped"] = f"{node!r} is not a devicetree label or path"
        blocks.append(b)
    conflicts = sorted(n for n, bs in nodes.items() if len({b["status"] for b in bs}) > 1)
    named = [b for b in blocks if b["node"]]
    doc = {"schema": "opendap.variant-devicetree/v1", "board": variant.data.get("board"), "variant": variant.name,
           "source": source,
           "counts": {"okay": sum(b["status"] == "okay" for b in named),
                      "disabled": sum(b["status"] == "disabled" for b in named),
                      "skipped": sum(1 for b in blocks if b["skipped"])},
           "conflicts": conflicts, "blocks": blocks}
    lines = [f"// Generated by odapkit variant from {source} (opendap.board-variant/v1); do not edit.",
             f"// Board {doc['board']}, variant {variant.name} ({variant.data.get('kind')}, "
             f"{variant.data.get('status')}): each block's node is enabled when the variant fits the block.",
             "/dts-v1/;", "/plugin/;", ""]
    for node in sorted(nodes):
        bs = nodes[node]
        status = "okay" if any(b["status"] == "okay" for b in bs) else "disabled"   # a fitted block needs its node
        ref = f"&{node}" if LABEL.fullmatch(node) else f"&{{{node}}}"
        why = "; ".join(f"{b['block']}: {b['state']}" + (f" {b['alternate']}" if b["alternate"] else "") +
                        (" (open)" if b["open"] else "") for b in bs)
        lines += [f"{ref} {{", f"\tstatus = \"{status}\"; /* {why} */", "};", ""]
    skipped = [b for b in blocks if b["skipped"]]
    if skipped:
        lines.append("/* Not in this fragment (no devicetree node named):")
        lines += [f" *   {b['block']} ({b['state']}): {b['skipped']}" for b in skipped]
        lines.append(" */")
    return doc, "\n".join(lines) + "\n"
