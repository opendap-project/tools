"""odw cli: Inventory every command-line surface and check it against the command standard

Usage: odw cli list  [--workspace DIR] [--root ROOT]... [--json]
       odw cli check [--workspace DIR] [--root ROOT]... [--no-probe] [--timeout S] [--jobs N]
                         [--write DIR] [--dry-run] [--json]

  list    the inventory: every executable in a public root's bin/, scripts/, tools/ and hooks/ folders and
          every Cargo binary target, with its §5 surface kind and whether it may be run
  check   the conformance test (command standard §8): runs the safe probes (--help, an unknown flag, a
          read-only --json call; stdin at end of file, no TTY, a timeout, sandboxed) on the executables that
          may be run, reads the others from source, and grades each against its row of §5. --json prints
          opendap.check-result/v1; --write DIR writes the matrix (opendap.matrix/v1) as
          DIR/cli-conformance.json and DIR/cli-conformance.md; --dry-run names the files and writes nothing

Examples:
  odw cli list --json
  odw cli check --root public/toolkit/host
  odw cli check --json --write matrices --dry-run

Exit status: 0 no executable fails (or list succeeded), 1 one fails, 2 usage error.
Errors: a dotted code, a hint and a fix on stderr; with --json, also an opendap.error/v1 document on stdout.
Spec: docs/specs/cli-conformance.md.
"""
import datetime as dt
import json
import pathlib
import sys

from odw import cli_inventory, cli_probe, cli_rules, clikit, evaluate, workspace

TOOL = "odw cli"
SUMMARY = __doc__.splitlines()[0].split(": ", 1)[1]
VERDICT = {"pass": "pass", "fail": "fail", "warning": "warn", "unverified": "skip", "info": "info"}


class UsageError(clikit.CliError):
    """A usage error: a stable code, a hint and a fix; exit 2 (odw.clikit)."""

    def __init__(self, code, message, hint, fix):
        super().__init__(code, message, hint, fix, status=2)


def summaries(ws, items):
    """{executable path: summary} for every entry of the roots' tools.toml files (cli_inventory.declarations)."""
    out = {}
    for root in sorted({e["root"] for e in items}):
        for path, (_, t) in cli_inventory.declarations(ws, root).items():
            out.setdefault(path, t.get("summary", ""))
    return out


def declared(items, probes):
    """{script path: (parent path, the call's result)} for each call a tools.toml names the script of (`reaches`)."""
    out = {}
    for e in items:
        runs = (probes.get(e["path"]) or {}).get("json_calls", [])
        for script, j in zip(e.get("json_reaches", []), runs):
            if script:
                out[script] = (e["path"], j)
    return out


def conformance(ws, items, probes):
    """The matrix (opendap.matrix/v1) of executables × §5 rules."""
    ctx = {"summaries": summaries(ws, items), "reached": declared(items, probes)}
    options = [{"id": e["path"], "name": e["name"], "group": e["root"],
                "attributes": {"kind": e["kind"], "probed": probes.get(e["path"]) is not None,
                               "not_run": e["probe_skipped"]}} for e in items]
    by = {e["path"]: e for e in items}
    criteria = [{"id": cid, "title": title, "kind": "hard",
                 "evaluate": (lambda o, cid=cid: cli_rules.cell(cid, by[o["id"]], probes.get(o["id"]), ctx))}
                for cid, title, _, _ in cli_rules.CRITERIA]
    study = evaluate.Study("cli-conformance", "Does every command-line surface hold to its row of the command "
                           "standard §5?", options, criteria, aggregation="worst-state", recommend=False)
    m = study.run()
    m["tool"] = {"name": TOOL}
    m["context"] = {"generated": f"@generated by {TOOL} check. Do not edit.", "date": dt.date.today().isoformat()}
    return m


def by_root(m):
    """Per root: executables, verdict counts and, per failing criterion, the executables that fail it."""
    roots = {}
    group = {o["id"]: o["group"] for o in m["options"]}
    for v in m["verdicts"]:
        r = roots.setdefault(group[v["option"]], {"executables": 0, "pass": 0, "incomplete": 0, "fail": 0, "failing": {}})
        r["executables"] += 1
        r[v["verdict"]] += 1
    for c in m["results"]:
        if c["state"] == "fail":
            failing = roots[group[c["option"]]]["failing"].setdefault(c["criterion"], [])
            failing.append(c["option"])
    return dict(sorted(roots.items()))


def check_result(m, ws):
    results = [{"id": f"{c['option']}#{c['criterion']}", "rule": f"command-standard §5 {c['criterion']}",
                "verdict": VERDICT[c["state"]], "message": c["why"], "location": {"path": c["option"]}}
               for c in m["results"] if c["state"] != "n/a"]
    return {"schema": "opendap.check-result/v1", "tool": {"name": TOOL}, "subject": {"repo": "workspace"},
            "generated": dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"), "results": results}


def render(m):
    lines = [evaluate.render_markdown(m).rstrip("\n"), "", "## By root", "",
             "| Root | Executables | Pass | Incomplete | Fail | Failing rules |", "|---|---|---|---|---|---|"]
    for root, r in by_root(m).items():
        failing = "; ".join(f"{c} ({len(v)})" for c, v in sorted(r["failing"].items())) or "none"
        lines.append(f"| {root} | {r['executables']} | {r['pass']} | {r['incomplete']} | {r['fail']} | {failing} |")
    return "\n".join(lines) + "\n"


def write(m, out, dry_run=False):
    out = pathlib.Path(out)
    files = {out / "cli-conformance.json": json.dumps(m, ensure_ascii=False, indent=1) + "\n",
             out / "cli-conformance.md": render(m)}
    for path, text in files.items():
        if dry_run:
            print(f"{TOOL}: would write {path}", file=sys.stderr)
        else:
            out.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    return [str(p) for p in files]


class Parser(clikit.Parser):
    def print_help(self, file=None):
        print(__doc__.rstrip(), file=file or sys.stdout)


def parser():
    ap = Parser(prog=TOOL, add_help=True)
    sub = ap.add_subparsers(dest="verb", parser_class=Parser)
    for verb in ("list", "check"):
        p = sub.add_parser(verb)
        p.add_argument("--workspace")
        p.add_argument("--root", action="append", default=[])
        p.add_argument("--json", action="store_true")
        if verb == "check":
            p.add_argument("--no-probe", action="store_true")
            p.add_argument("--timeout", type=float, default=20.0)
            p.add_argument("--jobs", type=int, default=4)
            p.add_argument("--write", metavar="DIR")
            p.add_argument("--dry-run", action="store_true")
    return ap


def run(args):
    ws = pathlib.Path(args.workspace) if args.workspace else workspace.root()
    if ws is None or not (ws / "repos.tsv").is_file():
        raise UsageError("workspace.not_found", "no workspace (no repos.tsv here or above)",
                         "run inside a workspace checkout or name one", f"{TOOL} {args.verb} --workspace DIR")
    known = cli_inventory.roots_in(ws / "repos.tsv")
    unknown = [r for r in args.root if r not in known]
    if unknown:
        raise UsageError("root.not_found", f"no root {', '.join(unknown)} in repos.tsv",
                         "a root is a path from the workspace's repos.tsv", f"{TOOL} list --json")
    items = cli_inventory.inventory(ws, roots=args.root or None)
    if args.verb == "list":
        if args.json:
            print(json.dumps(cli_inventory.document(items), ensure_ascii=False))
        else:
            for e in items:
                print(f"{e['kind']:<14} {e['path']}" + (f"  (not run: {e['probe_skipped']})" if not e["probe"] else ""))
        return 0
    probes = {} if args.no_probe else cli_probe.probe_all(items, ws, args.timeout, args.jobs)
    m = conformance(ws, items, probes)
    if args.write:
        write(m, args.write, args.dry_run)
    names = {o["id"]: o["name"] for o in m["options"]}
    if args.json:
        print(json.dumps(check_result(m, ws), ensure_ascii=False))
    else:
        for root, r in by_root(m).items():
            print(f"{root}: {r['executables']} executables, {r['pass']} pass, {r['incomplete']} incomplete, {r['fail']} fail")
            for c, paths in sorted(r["failing"].items()):
                print(f"  {c}: {', '.join(names[p] for p in paths)}")
    return 1 if any(v["verdict"] == "fail" for v in m["verdicts"]) else 0


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    as_json = "--json" in argv
    try:
        args = parser().parse_args(argv)
        if not args.verb:
            raise UsageError("input.missing_verb", "no verb (list or check)", "name a verb", f"{TOOL} --help")
        return run(args)
    except SystemExit as e:
        return 0 if not e.code else 2
    except clikit.CliError as e:
        return clikit.report(TOOL, e, as_json)


if __name__ == "__main__":
    sys.exit(main())
