"""odw owners: who owns what, from the workspace's owners.tsv, and the CODEOWNERS file generated from it.

owners.tsv is a tab-separated file at the workspace root with the header `path<TAB>owner`; lines starting with
`#` are comments. `path` is a glob over repository paths as repos.tsv writes them (`*` also crosses `/`; `.` is
the workspace repository itself), optionally followed by `:` and a CODEOWNERS pattern inside the repository
(default `*`). `owner` is one or more GitHub handles or teams separated by spaces (`@user`, `@org/team`). The
file is public, so it never names a private path. Rows apply in file order; in CODEOWNERS a later matching
pattern wins, as GitHub reads it.

`odw sync` generates `.github/CODEOWNERS` in every repository a row matches (sync.toml `[[generated]]`,
generator `codeowners`) and reports a file that differs. Schema: schemas/owners.schema.json.
Spec: docs/specs/workspace-sync.md (Generated files).
"""
import fnmatch
import pathlib

from odw import clikit, schemas

HEADER = ("path", "owner")
SOURCE_URL = "https://github.com/opendap-project/workspace/blob/main/owners.tsv"
BANNER = ("# @generated by odapkit sync from the workspace's owners.tsv. Do not edit:\n"
          f"# change {SOURCE_URL} and run odapkit sync --apply.\n")


def _invalid(path, message):
    return clikit.CliError("owners.invalid", f"{path}: {message}",
                           "owners.tsv has the header path<TAB>owner and one row per public path glob and owners",
                           "odw sync --check --json")


def read(path):
    """The rows of owners.tsv, in file order, as {path, owner}; CliError owners.invalid when it breaks its schema."""
    path = pathlib.Path(path)
    lines = [ln for ln in path.read_text().splitlines() if ln.strip() and not ln.lstrip().startswith("#")]
    if not lines or tuple(lines[0].split("\t")) != HEADER:
        raise _invalid(path, "the first line must be the header path<TAB>owner")
    rows = []
    for n, ln in enumerate(lines[1:], start=2):
        cells = ln.split("\t")
        if len(cells) != 2:
            raise _invalid(path, f"row {n} has {len(cells)} columns, not 2")
        rows.append({"path": cells[0].strip(), "owner": cells[1].strip()})
    errs = schemas.errors(rows, "owners")
    if errs:
        raise _invalid(path, "; ".join(errs))
    return rows


def _split(row):
    glob, _, pattern = row["path"].partition(":")
    return glob, pattern or "*"


def render(rows, repo):
    """The CODEOWNERS text for the repository at workspace path `repo`, or None when no row applies to it."""
    lines = [f"{pattern} {row['owner']}" for row in rows
             for glob, pattern in [_split(row)] if fnmatch.fnmatchcase(repo, glob)]
    return BANNER + "\n".join(lines) + "\n" if lines else None


def candidates(ws, repos):
    """The repositories a generated file may apply to: the workspace itself, then every repos.tsv path."""
    ws = pathlib.Path(ws)
    return [r for r in [".", *repos] if (ws / r / ".git").exists()]
