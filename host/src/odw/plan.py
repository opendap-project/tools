"""odw plan: a maintainers' programme as data — tasks/<id>.toml, decisions.toml, claims — and its index.

Usage:
    odapkit plan [--programme DIR] [--claims DIR] [--json] COMMAND
      list [--ready] [--phase N] [--status S]   tasks, in phase then id order
      next                                      the first ready task
      show ID                                   one task record
      check                                     schemas, file names, dependencies, decisions, cycles
      claim ID [--session S] [--hours H]        take a ready task: status doing, a claim file
      release ID                                drop your claim; the task goes back to todo
      done ID --evidence REPO=SHA... --docs P... [--tests T...]
      render [--check]                          write tasks/INDEX.md, or check it is current

The programme folder is --programme, else $ODAP_PROGRAMME, else the nearest folder at or above the current one
that holds decisions.toml and tasks/. Claims live in <workspace>/.state/claims (outside git). A task is ready when
its status is todo, every task it depends on is done and every decision blocking it is decided.
Exit status: 0 ok, 1 a check failed or the action was refused, 2 usage error. Spec: docs/specs/programme-plan.md.
"""
import argparse
import datetime as dt
import getpass
import json
import os
import pathlib
import socket
import sys
import tomllib

from odw import schemas, workspace

FIELDS = ("id", "phase", "title", "source", "repos", "files", "depends_on", "blocked_by", "status", "visibility",
          "tests", "docs", "evidence", "notes")
PHASES = {-1: "Control", 0: "Hygiene", 1: "Single sources", 2: "Hardware thread", 3: "Software architecture",
          4: "Image and extensibility", 5: "Topology cutover", 6: "Lifecycle"}
HEADER = "<!-- @generated by odw plan render from tasks/*.toml and decisions.toml. Do not edit. -->"


class PlanError(Exception):
    pass


def _now():
    return dt.datetime.now(dt.timezone.utc).replace(microsecond=0)


def _iso(t):
    return t.strftime("%Y-%m-%dT%H:%M:%SZ")


def _value(v):
    if isinstance(v, dict):
        return "{ " + ", ".join(f"{json.dumps(k)} = {json.dumps(x)}" for k, x in v.items()) + " }" if v else "{}"
    return json.dumps(v, ensure_ascii=False)


def dump_task(t):
    return "".join(f"{k} = {_value(t[k])}\n" for k in FIELDS)


def find_programme(start=None):
    env = os.environ.get("ODAP_PROGRAMME")
    if env:
        return pathlib.Path(env)
    d = pathlib.Path(start or os.getcwd()).resolve()
    for p in (d, *d.parents):
        if (p / "decisions.toml").is_file() and (p / "tasks").is_dir():
            return p
    return None


class Programme:
    def __init__(self, root, claims_dir=None):
        self.root = pathlib.Path(root)
        if claims_dir is None:
            state = workspace.state_dir(self.root)
            claims_dir = state / "claims" if state else self.root / ".claims"
        self.claims_dir = pathlib.Path(claims_dir)

    # ---- reading ----
    def _files(self):
        return sorted((self.root / "tasks").glob("*.toml"))

    def tasks(self):
        out = []
        for f in self._files():
            t = tomllib.loads(f.read_text())
            t["_file"] = f.name
            out.append(t)
        return sorted(out, key=lambda t: (t.get("phase", 99), t.get("id", "")))

    def task(self, tid):
        path = self.root / "tasks" / f"{tid}.toml"
        if not path.is_file():
            raise PlanError(f"no task {tid}")
        return tomllib.loads(path.read_text())

    def decisions(self):
        doc = tomllib.loads((self.root / "decisions.toml").read_text())
        return {d["id"]: d for d in doc.get("decision", [])}

    def _is_ready(self, t, status, decided):
        return (t.get("status") == "todo" and all(status.get(d) == "done" for d in t.get("depends_on", []))
                and all(decided.get(b) == "decided" for b in t.get("blocked_by", [])))

    def ready(self):
        ts = self.tasks()
        status = {t["id"]: t["status"] for t in ts}
        decided = {k: v["status"] for k, v in self.decisions().items()}
        return [t for t in ts if self._is_ready(t, status, decided)]

    def next(self):
        r = self.ready()
        return r[0] if r else None

    # ---- checking ----
    def check(self):
        problems = []
        ts = self.tasks()
        ids = {t.get("id") for t in ts}
        decs = self.decisions()
        for e in schemas.errors(tomllib.loads((self.root / "decisions.toml").read_text()), "decisions"):
            problems.append(f"decisions.toml: {e}")
        for t in ts:
            name = t.pop("_file")
            for e in schemas.errors(t, "task"):
                problems.append(f"{name}: {e}")
            if name != f"{t.get('id')}.toml":
                problems.append(f"{name}: file name does not match id {t.get('id')}")
            for d in t.get("depends_on", []):
                if d not in ids:
                    problems.append(f"{name}: depends on unknown task {d}")
            for b in t.get("blocked_by", []):
                if b not in decs:
                    problems.append(f"{name}: blocked by unknown decision {b}")
        graph = {t["id"]: [d for d in t.get("depends_on", []) if d in ids] for t in ts if "id" in t}
        seen, stack = {}, []

        def visit(n):
            seen[n] = 1
            stack.append(n)
            for m in graph.get(n, []):
                if seen.get(m) == 1:
                    problems.append("dependency cycle: " + " -> ".join(stack[stack.index(m):] + [m]))
                elif m not in seen:
                    visit(m)
            stack.pop()
            seen[n] = 2

        for n in sorted(graph):
            if n not in seen:
                visit(n)
        return problems

    # ---- writing ----
    def _write(self, t):
        t = {k: t[k] for k in FIELDS}
        errs = schemas.errors(t, "task")
        if errs:
            raise PlanError(f"{t['id']}: " + "; ".join(errs))
        (self.root / "tasks" / f"{t['id']}.toml").write_text(dump_task(t))

    def _claim_path(self, tid):
        return self.claims_dir / f"{tid}.toml"

    def claim_of(self, tid):
        p = self._claim_path(tid)
        return tomllib.loads(p.read_text()) if p.is_file() else None

    def claim(self, tid, session, hours=4):
        t = self.task(tid)
        held = self.claim_of(tid)
        live = held and dt.datetime.fromisoformat(held["expires"].replace("Z", "+00:00")) > _now()
        if live and held["session"] != session:
            raise PlanError(f"{tid} is claimed by {held['session']} until {held['expires']}")
        if not live:
            ts = self.tasks()
            status = {x["id"]: x["status"] for x in ts}
            decided = {k: v["status"] for k, v in self.decisions().items()}
            if t["status"] not in ("todo", "doing") or (t["status"] == "todo" and not self._is_ready(t, status, decided)):
                raise PlanError(f"{tid} is not ready (status {t['status']}, dependencies or decisions open)")
        self.claims_dir.mkdir(parents=True, exist_ok=True)
        now = _now()
        self._claim_path(tid).write_text(
            f'task = "{tid}"\nsession = {json.dumps(session)}\nsince = "{_iso(now)}"\n'
            f'expires = "{_iso(now + dt.timedelta(hours=hours))}"\n')
        t["status"] = "doing"
        self._write(t)

    def release(self, tid):
        t = self.task(tid)
        self._claim_path(tid).unlink(missing_ok=True)
        if t["status"] == "doing":
            t["status"] = "todo"
            self._write(t)

    def done(self, tid, evidence, docs, tests=()):
        if not evidence:
            raise PlanError(f"{tid}: done needs at least one evidence commit (REPO=SHA)")
        t = self.task(tid)
        t.update(status="done", evidence=dict(evidence), docs=list(docs), tests=list(tests))
        self._write(t)
        self._claim_path(tid).unlink(missing_ok=True)

    # ---- index ----
    def render(self):
        ts = self.tasks()
        status = {t["id"]: t["status"] for t in ts}
        decs = self.decisions()
        decided = {k: v["status"] for k, v in decs.items()}
        ready = sum(self._is_ready(t, status, decided) for t in ts)
        lines = [HEADER, "", "# Task index", "",
                 f"{len(ts)} tasks, {ready} ready, {sum(s == 'done' for s in status.values())} done; "
                 f"{sum(v == 'open' for v in decided.values())} open decisions. Ready = `todo`, every dependency done, "
                 "no open blocking decision.", ""]
        for ph in sorted({t["phase"] for t in ts}):
            group = [t for t in ts if t["phase"] == ph]
            lines += [f"## Phase {ph}: {PHASES.get(ph, '')} ({len(group)})", "",
                      "| Task | Title | Status | Depends on | Blocked by |", "|---|---|---|---|---|"]
            for t in group:
                s = "ready" if self._is_ready(t, status, decided) else t["status"]
                title = t["title"].replace("|", "/").replace("*", "\\*")
                open_b = ", ".join(b for b in t["blocked_by"] if decided.get(b) != "decided")
                lines.append(f"| {t['id']} | {title} | {s} | {', '.join(t['depends_on'])} | {open_b} |")
            lines.append("")
        return "\n".join(lines)

    def index_path(self):
        return self.root / "tasks" / "INDEX.md"

    def write_index(self):
        self.index_path().write_text(self.render())

    def index_is_current(self):
        p = self.index_path()
        return p.is_file() and p.read_text() == self.render()


def _norm(text):
    return " ".join(text.lower().split())


def _homes(self, ws):
    """Rules the programme introduced that live nowhere else: no home, or a home that no longer states them.
    A rule waiting for a decision (`pending`) is not reported."""
    f = self.root / "homes.toml"
    if not f.is_file():
        return []
    doc = tomllib.loads(f.read_text())
    out = []
    for r in doc.get("rule", []):
        if r.get("pending"):
            continue
        homes = r.get("homes", [])
        if not homes:
            out.append({"rule": r["id"], "problem": "no home", "detail": r["rule"]})
            continue
        for h in homes:
            path = pathlib.Path(ws) / h["path"]
            if not path.is_file():
                out.append({"rule": r["id"], "problem": "home missing", "detail": h["path"]})
            elif _norm(h["contains"]) not in _norm(path.read_text()):
                out.append({"rule": r["id"], "problem": "home lacks the rule", "detail": f"{h['path']}: {h['contains']}"})
    return out


Programme.homes = _homes


def _session():
    return os.environ.get("ODAP_SESSION") or f"{getpass.getuser()}@{socket.gethostname()}:{os.getppid()}"


def main(argv=None):
    ap = argparse.ArgumentParser(prog="odapkit plan", description="A maintainers' programme as data.")
    ap.add_argument("--programme")
    ap.add_argument("--claims")
    ap.add_argument("--json", action="store_true")
    sub = ap.add_subparsers(dest="cmd", required=True)
    ls = sub.add_parser("list")
    ls.add_argument("--ready", action="store_true")
    ls.add_argument("--phase", type=int)
    ls.add_argument("--status")
    ls.add_argument("--json", action="store_true", dest="json_sub")
    sub.add_parser("next")
    sub.add_parser("check")
    for name in ("show", "release"):
        sub.add_parser(name).add_argument("id")
    cl = sub.add_parser("claim")
    cl.add_argument("id")
    cl.add_argument("--session", default=None)
    cl.add_argument("--hours", type=float, default=4)
    dn = sub.add_parser("done")
    dn.add_argument("id")
    dn.add_argument("--evidence", nargs="+", action="extend", required=True, metavar="REPO=SHA")
    dn.add_argument("--docs", nargs="+", action="extend", required=True)
    dn.add_argument("--tests", nargs="*", action="extend", default=[])
    hm = sub.add_parser("homes", help="rules found only in the programme (homes.toml)")
    hm.add_argument("--workspace")
    rd = sub.add_parser("render")
    rd.add_argument("--check", action="store_true")
    try:
        args = ap.parse_args(argv)
    except SystemExit as e:
        return 2 if e.code else 0
    root = pathlib.Path(args.programme) if args.programme else find_programme()
    if root is None:
        print("odapkit plan: no programme here (use --programme or ODAP_PROGRAMME)", file=sys.stderr)
        return 2
    prog = Programme(root, claims_dir=args.claims)
    as_json = args.json or getattr(args, "json_sub", False)

    def show(tasks):
        if as_json:
            print(json.dumps([{k: t[k] for k in FIELDS if k in t} for t in tasks], ensure_ascii=False, indent=1))
        else:
            for t in tasks:
                print(f"{t['id']:8} {t['phase']:>2} {t['status']:7} {t['title']}")

    try:
        if args.cmd == "list":
            ts = prog.ready() if args.ready else prog.tasks()
            ts = [t for t in ts if (args.phase is None or t["phase"] == args.phase) and (not args.status or t["status"] == args.status)]
            show(ts)
        elif args.cmd == "next":
            t = prog.next()
            show([t] if t else [])
            return 0 if t else 1
        elif args.cmd == "show":
            t = prog.task(args.id)
            print(json.dumps(t, ensure_ascii=False, indent=1) if as_json else dump_task(t), end="" if not as_json else "\n")
        elif args.cmd == "check":
            problems = prog.check()
            if as_json:
                print(json.dumps(problems, indent=1))
            else:
                for p in problems:
                    print(p)
            return 1 if problems else 0
        elif args.cmd == "claim":
            prog.claim(args.id, session=args.session or _session(), hours=args.hours)
        elif args.cmd == "release":
            prog.release(args.id)
        elif args.cmd == "done":
            ev = dict(e.split("=", 1) for e in args.evidence)
            prog.done(args.id, evidence=ev, docs=args.docs, tests=args.tests)
        elif args.cmd == "homes":
            ws = pathlib.Path(args.workspace) if args.workspace else workspace.root(root)
            found = prog.homes(ws)
            if as_json:
                print(json.dumps(found, ensure_ascii=False, indent=1))
            else:
                for f in found:
                    print(f"{f['rule']}: {f['problem']} ({f['detail']})")
            return 1 if found else 0
        elif args.cmd == "render":
            if args.check:
                if prog.index_is_current():
                    return 0
                print("tasks/INDEX.md is not current: run odapkit plan render", file=sys.stderr)
                return 1
            prog.write_index()
    except PlanError as e:
        print(f"odapkit plan: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
