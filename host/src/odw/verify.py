"""odw verify: verification matrices as data (opendap.verification/v1).

Usage:
    odapkit verify render MATRIX [--check]                 the Markdown beside the matrix (MATRIX with .md)
    odapkit verify collect MATRIX --results DIR... [--check] results of the cases' checks, by variant
    odapkit verify coverage MATRIX [--prefix P...]          requirements no case verifies

A matrix declares its vocabulary ([matrix]: statuses, levels, which statuses count as done, which levels are by
hand only) and one [[case]] per row. A case is observed by hand (status, observed, evidence) and may name `checks`:
the ids of opendap.check-result/v1 results that prove it again. `collect` joins those results, per variant, into
MATRIX.collected.json (generated, never edited: results are referenced by path and commit, never copied by hand).
Exit status: 0 ok, 1 a problem, a stale file or an uncovered requirement, 2 usage. Spec: docs/specs/verification.md.
"""
import argparse
import json
import pathlib
import sys
import tomllib
from collections import Counter, OrderedDict

from odw import requirements, schemas, workspace

GEN = "<!-- @generated by odapkit verify from {source}: edit the data, then run it. -->"


def sidecar(matrix):
    p = pathlib.Path(matrix)
    return p.with_name(p.stem + ".collected.json")


def load(matrix):
    doc = tomllib.loads(pathlib.Path(matrix).read_text())
    side = sidecar(matrix)
    if side.is_file():
        collected = json.loads(side.read_text())
        for c in doc.get("case", []):
            if c["id"] in collected:
                c["collected"] = collected[c["id"]]
    return doc


def problems(doc):
    out = list(schemas.errors(doc, "verification"))
    statuses = {s["id"] for s in doc["matrix"]["status"]}
    levels = {lv["id"] for lv in doc["matrix"]["level"]}
    done = set(doc["matrix"].get("done", []))
    seen = set()
    for c in doc.get("case", []):
        cid = c.get("id", "?")
        if cid in seen:
            out.append(f"duplicate id {cid}")
        seen.add(cid)
        if c.get("status") not in statuses:
            out.append(f"{cid}: unknown status {c.get('status')}")
        for lv in c.get("levels", []):
            if lv not in levels:
                out.append(f"{cid}: unknown level {lv}")
        if c.get("status") in done and not c.get("levels"):
            out.append(f"{cid}: {c['status']} at no level")
        for variant, col in c.get("collected", {}).items():
            if col["state"] == "fail" and c.get("status") in done:
                out.append(f"{cid}: {c['status']} but its checks fail on {variant}")
    return out


def _results(dirs):
    for d in dirs:
        for f in sorted(pathlib.Path(d).rglob("*.json")):
            try:
                doc = json.loads(f.read_text())
            except (OSError, json.JSONDecodeError):
                continue
            # Other JSON lives beside results (a runner's own report, a list): only check results count.
            if not isinstance(doc, dict) or doc.get("schema") != "opendap.check-result/v1":
                continue
            subject = doc.get("subject", {})
            for r in doc.get("results", []):
                yield f, subject, r


def collect(doc, dirs):
    found = {}
    for path, subject, r in _results(dirs):
        found.setdefault(r["id"], []).append((path, subject, r))
    for c in doc.get("case", []):
        c.pop("collected", None)
        if not c.get("checks"):
            continue
        by_variant = {}
        for check in c["checks"]:
            for path, subject, r in found.get(check, []):
                v = subject.get("variant", "default")
                by_variant.setdefault(v, []).append({"path": str(path), "commit": subject.get("commit", ""), "id": r["id"], "verdict": r["verdict"]})
        if not by_variant:
            by_variant = {"default": []}
        col = {}
        for v, rs in sorted(by_variant.items()):
            verdicts = {x["verdict"] for x in rs}
            state = "missing" if not rs else "fail" if verdicts & {"fail", "error"} else "warn" if "warn" in verdicts else "pass"
            col[v] = {"state": state, "results": sorted(rs, key=lambda x: (x["id"], x["path"]))}
        c["collected"] = col
    return doc


def _collected_json(doc):
    return json.dumps({c["id"]: c["collected"] for c in doc.get("case", []) if "collected" in c}, indent=1, sort_keys=True) + "\n"


def write(matrix, doc):
    sidecar(matrix).write_text(_collected_json(doc))


def is_current(matrix, dirs):
    side = sidecar(matrix)
    return side.is_file() and side.read_text() == _collected_json(collect(load(matrix), dirs))


def cell(s):
    return str(s).replace("|", "\\|").replace("\n", " ")


def render(doc, source):
    m = doc["matrix"]
    statuses = OrderedDict((s["id"], s["meaning"]) for s in m["status"])
    levels = OrderedDict((lv["id"], lv["meaning"]) for lv in m["level"])
    cases = doc.get("case", [])
    areas = list(OrderedDict.fromkeys(c["area"] for c in cases))
    count = Counter((c["area"], c["status"]) for c in cases)
    total = Counter(c["status"] for c in cases)
    out = [GEN.format(source=source), "", f"# {m['title']}", ""]
    if m.get("intro"):
        out += [m["intro"], ""]
    out += ["**Status:** " + " · ".join(f"*{k}*: {v}" for k, v in statuses.items()) + "." + (" " + m["status_note"] if m.get("status_note") else ""), "",
            "**Levels**" + (f" {m['level_note']}" if m.get("level_note") else ":") + " " + " · ".join(f"*{k}*: {v}" for k, v in levels.items()) + "." + (" " + m["level_after"] if m.get("level_after") else ""), "",
            "## Coverage", "", "| Area | " + " | ".join(statuses) + " | Cases |", "|---|" + "---|" * (len(statuses) + 1)]
    for a in areas:
        n = sum(count[(a, s)] for s in statuses)
        out.append(f"| {a} | " + " | ".join(str(count[(a, s)] or "") for s in statuses) + f" | {n} |")
    out.append("| **All** | " + " | ".join(f"**{total[s]}**" for s in statuses) + f" | **{len(cases)}** |")
    done = [c for c in cases if c["status"] in m.get("done", [])]
    manual = set(m.get("manual", []))
    by_level = Counter(lv for c in done for lv in c["levels"])
    manual_only = [c["id"] for c in done if c["levels"] and set(c["levels"]) <= manual]
    out += ["", "### By level", "", f"Of the {len(done)} cases " + (m.get("done_label") or " or ".join(m.get("done", []))) + ":", "", "| Level | Cases |", "|---|---|"]
    out += [f"| {lv} | {by_level[lv]} |" for lv in levels]
    out += ["", f"**Seen only by hand ({len(manual_only)})**, waiting for a level that runs again: " + (", ".join(manual_only) or "none") + "."]
    for a in areas:
        out += ["", f"## {a[0].upper() + a[1:]}", "", "| Id | Primitive | Conditions | Case | Expected | Observed | Evidence | Status | Levels |",
                "|---|---|---|---|---|---|---|---|---|"]
        for c in (c for c in cases if c["area"] == a):
            conds = ", ".join(c.get("conditions", [])) or "—"
            status = f"{c['status']} ({c['date']})" if c.get("date") else c["status"]
            col = c.get("collected")
            if col:
                status += " · checks: " + ", ".join(f"{v} {x['state']}" for v, x in col.items())
            out.append("| " + " | ".join(cell(x) for x in [c["id"], c.get("primitive", ""), conds, c["case"], c["expected"], c.get("observed", "—"),
                                                              c.get("evidence", "—"), status, " ".join(c["levels"]) or "—"]) + " |")
    return "\n".join(out) + "\n"


def uncovered(doc, reqs):
    covered = {r for c in doc.get("case", []) for r in c.get("verifies", [])}
    return [r["id"] for r in reqs if r.get("status") in ("confirmed", "draft") and r["id"] not in covered]


def main(argv=None):
    ap = argparse.ArgumentParser(prog="odapkit verify", description="Verification matrices as data.")
    sub = ap.add_subparsers(dest="cmd", required=True)
    rd = sub.add_parser("render")
    rd.add_argument("matrix")
    rd.add_argument("--check", action="store_true")
    co = sub.add_parser("collect")
    co.add_argument("matrix")
    co.add_argument("--results", nargs="+", required=True)
    co.add_argument("--check", action="store_true")
    cv = sub.add_parser("coverage")
    cv.add_argument("matrix")
    cv.add_argument("--workspace")
    cv.add_argument("--prefix", nargs="+", help="only requirements with these id prefixes (e.g. SYS)")
    try:
        args = ap.parse_args(argv)
    except SystemExit as e:
        return 2 if e.code else 0
    matrix = pathlib.Path(args.matrix)
    doc = load(matrix)
    probs = problems(doc)
    for p in probs:
        print(f"{matrix}: {p}", file=sys.stderr)
    if args.cmd == "render":
        md = render(doc, matrix.name)
        target = matrix.with_suffix(".md")
        if args.check:
            ok = target.is_file() and target.read_text() == md
            if not ok:
                print(f"{target} is not current: run odapkit verify render {matrix}", file=sys.stderr)
            return 0 if ok and not probs else 1
        target.write_text(md)
        return 1 if probs else 0
    if args.cmd == "collect":
        if args.check:
            ok = is_current(matrix, args.results)
            if not ok:
                print(f"{sidecar(matrix)} is not current: run odapkit verify collect", file=sys.stderr)
            return 0 if ok else 1
        write(matrix, collect(doc, args.results))
        return 0
    ws = pathlib.Path(args.workspace) if args.workspace else workspace.root()
    if ws is None:
        print("odapkit verify: not inside a workspace", file=sys.stderr)
        return 2
    reqs = requirements.index(ws)
    if args.prefix:
        reqs = [r for r in reqs if r["id"].split("-")[0] in args.prefix]
    missing = uncovered(doc, reqs)
    for r in missing:
        print(r)
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main())
