"""odw owners: owners.tsv is read and validated, and each public repository's .github/CODEOWNERS is generated from it."""
import pytest

from odw import clikit, owners, sync

OWNERS = "path\towner\n# every public repository\npublic/*\t@maintainer\n.\t@maintainer\npublic/a:/docs/\t@maintainer @org/docs\n"
MANIFEST = """\
schema = "opendap.sync/v1"

[[generated]]
generator = "codeowners"
source = "owners.tsv"
target = ".github/CODEOWNERS"
repos = [".", "public/*"]
"""


@pytest.fixture
def ws(tmp_path):
    (tmp_path / "repos.tsv").write_text("path\trepository\npublic/a\to/a\npublic/b\to/b\n")
    (tmp_path / "owners.tsv").write_text(OWNERS)
    (tmp_path / ".git").mkdir()
    for r in "ab":
        (tmp_path / "public" / r / ".git").mkdir(parents=True)
    (tmp_path / "templates").mkdir()
    (tmp_path / "templates" / "sync.toml").write_text(MANIFEST)
    return tmp_path


def test_rows_are_read_in_order_without_comments(ws):
    rows = owners.read(ws / "owners.tsv")
    assert [(r["path"], r["owner"]) for r in rows] == [
        ("public/*", "@maintainer"), (".", "@maintainer"), ("public/a:/docs/", "@maintainer @org/docs")]


@pytest.mark.parametrize("text, code", [
    ("path\towner\nprivate/x\t@maintainer\n", "owners.invalid"),   # owners.tsv is public: no private paths
    ("path\towner\npublic/*\tmaintainer\n", "owners.invalid"),     # a handle starts with @
    ("path\towner\npublic/*\n", "owners.invalid"),                 # two columns
    ("repo\towner\npublic/*\t@m\n", "owners.invalid"),             # the header names the columns
])
def test_invalid_files_are_refused(tmp_path, text, code):
    (tmp_path / "owners.tsv").write_text(text)
    with pytest.raises(clikit.CliError) as e:
        owners.read(tmp_path / "owners.tsv")
    assert e.value.code == code


def test_render_per_repository(ws):
    rows = owners.read(ws / "owners.tsv")
    a = owners.render(rows, "public/a")
    assert a.splitlines()[-2:] == ["* @maintainer", "/docs/ @maintainer @org/docs"]
    assert a.startswith("# @generated by odapkit sync")
    assert owners.render(rows, "public/b").splitlines()[-1] == "* @maintainer"
    assert owners.render(rows, ".").splitlines()[-1] == "* @maintainer"
    assert owners.render(rows, "private/x") is None


def test_sync_check_reports_missing_codeowners_and_apply_repairs(ws):
    found = sorted((d.repo, d.target, d.state) for d in sync.check(ws, ws / "templates"))
    assert found == [(".", ".github/CODEOWNERS", "missing"), ("public/a", ".github/CODEOWNERS", "missing"),
                     ("public/b", ".github/CODEOWNERS", "missing")]
    assert len(sync.apply(ws, ws / "templates")) == 3
    assert (ws / "public/b/.github/CODEOWNERS").read_text().endswith("* @maintainer\n")
    assert sync.check(ws, ws / "templates") == []


def test_sync_check_reports_a_hand_edited_codeowners(ws):
    sync.apply(ws, ws / "templates")
    (ws / "public/a/.github/CODEOWNERS").write_text("* @someone-else\n")
    assert [(d.repo, d.state) for d in sync.check(ws, ws / "templates")] == [("public/a", "differs")]


def test_sync_cli_refuses_an_invalid_owners_file(ws, capsys):
    (ws / "owners.tsv").write_text("path\towner\nprivate/x\t@m\n")
    assert sync.main(["--workspace", str(ws), "--templates", str(ws / "templates"), "--check", "--json"]) == 1
    assert '"code": "owners.invalid"' in capsys.readouterr().out
