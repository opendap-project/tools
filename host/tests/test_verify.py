"""odw verify: verification matrices as data (opendap.verification/v1), results collected from check-result."""
import json
import shutil

import pytest

from odw import schemas, verify

FIX = __import__("pathlib").Path(__file__).parent / "fixtures" / "verification"


@pytest.fixture
def matrix(tmp_path):
    p = tmp_path / "matrix.toml"
    shutil.copy(FIX / "matrix.toml", p)
    return p


def result(tmp_path, verdict, variant="virtual-t1", rid="gesture-tap", name="r.json"):
    d = tmp_path / "results"
    d.mkdir(exist_ok=True)
    doc = {"schema": "opendap.check-result/v1", "tool": {"name": "e2e"}, "subject": {"repo": "public/system", "variant": variant, "commit": "0000000"},
           "generated": "2026-10-26T10:00:00Z", "results": [{"id": rid, "verdict": verdict, "message": "x"}]}
    (d / name).write_text(json.dumps(doc))
    return d


def test_fixture_matrix_is_valid(matrix):
    doc = verify.load(matrix)
    assert schemas.errors(doc, "verification") == []
    assert verify.problems(doc) == []


def test_problems_unknown_status_level_duplicate_and_done_without_level(matrix):
    doc = verify.load(matrix)
    doc["case"][1].update(status="unit")
    doc["case"].append(dict(doc["case"][0]))
    doc["case"][0]["levels"] = ["L9"]
    probs = verify.problems(doc)
    assert any("duplicate id tap" in p for p in probs)
    assert any("unknown level L9" in p for p in probs)
    assert any("long: unit at no level" in p for p in probs)


def test_render_counts_by_area_and_status(matrix):
    md = verify.render(verify.load(matrix), source="matrix.toml")
    assert md.startswith("<!-- @generated by odapkit verify")
    assert "| gestures | 1 |  | 1 | 2 |" in md
    assert "**Seen only by hand (0)**" in md


def test_collect_records_results_by_variant(matrix, tmp_path):
    results = result(tmp_path, "pass")
    doc = verify.collect(verify.load(matrix), [results])
    col = doc["case"][0]["collected"]["virtual-t1"]
    assert col["state"] == "pass" and col["results"][0]["id"] == "gesture-tap"
    assert "collected" not in doc["case"][1]


def test_collect_skips_other_json_beside_results(matrix, tmp_path):
    results = result(tmp_path, "pass")
    (results / "report.json").write_text('[{"scenario": "a runner\'s own report, a list"}]')
    (results / "notes.json").write_text('{"not": "a check result"}')
    doc = verify.collect(verify.load(matrix), [results])
    assert doc["case"][0]["collected"]["virtual-t1"]["state"] == "pass"


def test_collect_fail_contradicting_a_verified_case_is_a_problem(matrix, tmp_path):
    doc = verify.collect(verify.load(matrix), [result(tmp_path, "fail")])
    assert doc["case"][0]["collected"]["virtual-t1"]["state"] == "fail"
    assert any("tap: verified but its checks fail on virtual-t1" in p for p in verify.problems(doc))


def test_check_detects_stale_collection(matrix, tmp_path):
    results = result(tmp_path, "pass")
    verify.write(matrix, verify.collect(verify.load(matrix), [results]))
    assert verify.is_current(matrix, [results])
    result(tmp_path, "fail")
    assert not verify.is_current(matrix, [results])


def test_coverage_lists_requirements_without_a_case():
    reqs = [{"id": "SYS-046", "status": "confirmed"}, {"id": "SYS-047", "status": "confirmed"}, {"id": "SYS-048", "status": "withdrawn"}]
    doc = {"case": [{"id": "tap", "verifies": ["SYS-046"]}]}
    assert verify.uncovered(doc, reqs) == ["SYS-047"]


def test_a_measurement_without_a_limit_is_measured_never_pass(matrix, tmp_path):
    results = result(tmp_path, "info")
    doc = verify.collect(verify.load(matrix), [results])
    assert doc["case"][0]["collected"]["virtual-t1"]["state"] == "measured"
    assert schemas.errors(doc, "verification") == []
